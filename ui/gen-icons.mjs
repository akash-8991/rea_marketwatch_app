// Writes src/marketlens/static/js/icons.js from the Lucide icon set (https://lucide.dev, ISC licence): only the icons the app uses, as path data.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const NAMES = `search star plus x check chevron-down chevron-right arrow-up arrow-down arrow-up-down minus clock wifi-off triangle-alert circle-check info
layout-dashboard chart-line list-filter building-2 newspaper wallet play pause refresh-cw settings-2 moon sun log-out menu command trending-up trending-down
trash-2 circle-dot database zap history flask-conical chart-candlestick rotate-ccw briefcase receipt activity panel-left circle-x circle-alert download upload
calendar sliders-horizontal bell columns-3 bookmark layers target scale shield-check`.split(/\s+/);

const body = (name) => {
  const svg = readFileSync(join(here, 'node_modules', 'lucide-static', 'icons', `${name}.svg`), 'utf8');
  return svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').replace(/ \/>/g, '/>').trim();
};
const map = Object.fromEntries(NAMES.map((n) => [n, body(n)]));
const out = `/* Generated by ui/gen-icons.mjs from Lucide (https://lucide.dev, ISC licence, see docs/THIRD_PARTY.md). Do not edit by hand. */
const PATHS = ${JSON.stringify(map, null, 1)};

/** Lucide icon as inline SVG: stroke uses currentColor, so it follows text colour and themes; decorative unless a label is given. */
export function lucide(name, size = 16, cls = '', label = '') {
  const p = PATHS[name];
  if (!p) return '';
  const a11y = label ? \`role="img" aria-label="\${label}"\` : 'aria-hidden="true" focusable="false"';
  return \`<svg class="lucide \${cls}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" \${a11y}>\${p}</svg>\`;
}
export const hasIcon = (name) => name in PATHS;
`;
writeFileSync(join(here, '..', 'src', 'marketlens', 'static', 'js', 'icons.js'), out);
console.log('icons.js:', NAMES.length, 'icons,', out.length, 'bytes');
